"""row8_construct.py: the constructions of Lemmas 3.1 and 3.3 of the paper for z(8,n;4,4), n >= 36.

Columns are subsets of the 8 rows. P = Tan's 36 five-subsets of {0..7} (base sets 01236 01345 01346 01356 01456 03467
03567 04567 under the cyclic group generated by (012)(345)(67); every four-subset lies in at most three of them).
  36 <= n <= 210: x = min(36, floor((210 - n)/4)) members of P, then n - x four-subsets, each four-set Q used at most
                  3 - (number of chosen five-sets containing Q) times, in lexicographic order of Q;
                  ones = 4n + x, i.e. 4n + 36 for n <= 66 and floor((210 + 15n)/4) for 63 <= n <= 210;
  n >= 210:       every four-subset three times and n - 210 columns {0,1,2}; ones = 3n + 210.
Writes the TRANSPOSE (n rows of 8 characters, row j = column j), which has no all-ones 4 x 4 submatrix exactly when the
8 x n matrix has none, so both checkers can read it for any n. Prints n, the number of ones and the formula value.
Usage: python3 -I row8_construct.py n OUT.mat"""
import sys
from itertools import combinations

n, out = int(sys.argv[1]), sys.argv[2]
assert n >= 36
sig = {0: 1, 1: 2, 2: 0, 3: 4, 4: 5, 5: 3, 6: 7, 7: 6}
P = set()
for b in ["01236", "01345", "01346", "01356", "01456", "03467", "03567", "04567"]:
    x = tuple(sorted(int(c) for c in b))
    for _ in range(6):
        P.add(x)
        x = tuple(sorted(sig[i] for i in x))
P = sorted(P)
assert len(P) == 36
fours = list(combinations(range(8), 4))
if n >= 210:
    cols = [Q for Q in fours for _ in range(3)] + [(0, 1, 2)] * (n - 210)
    formula = 3 * n + 210
else:
    x = min(36, (210 - n) // 4)
    chosen = P[:x]
    load = {Q: 0 for Q in fours}
    for f in chosen:
        for Q in combinations(f, 4):
            load[Q] += 1
    spare = [Q for Q in fours for _ in range(3 - load[Q])]
    assert len(spare) >= n - x
    cols = chosen + spare[: n - x]
    formula = 4 * n + 36 if n <= 66 else (210 + 15 * n) // 4
assert len(cols) == n
ones = sum(len(c) for c in cols)
with open(out, "w") as f:
    for c in cols:
        f.write("".join("1" if i in c else "0" for i in range(8)) + "\n")
print(f"n={n} ones={ones} formula={formula}")
